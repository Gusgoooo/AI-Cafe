import { SessionArc, SessionArcPhase } from '@/types'

export const DEFAULT_SESSION_ARC: SessionArc = {
  phases: [
    { name: 'introduction', start: 0, end: 0.05 },
    { name: 'iceBreaking', start: 0.05, end: 0.12 },
    { name: 'warmingUp', start: 0.12, end: 0.25 },
    { name: 'peakEngagement', start: 0.25, end: 0.55 },
    { name: 'plateau', start: 0.55, end: 0.75 },
    { name: 'windingDown', start: 0.75, end: 0.9 },
    { name: 'closing', start: 0.9, end: 1.0 },
  ],
}

export function getCurrentPhase(progress: number, arc: SessionArc = DEFAULT_SESSION_ARC): SessionArcPhase {
  const clamped = Math.max(0, Math.min(1, progress))
  return arc.phases.find(p => clamped >= p.start && clamped < p.end) ?? arc.phases[arc.phases.length - 1]
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

